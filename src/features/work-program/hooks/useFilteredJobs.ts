export function useFilteredJobs(
  jobs: any[],
  viewType: string
) {

  return jobs.filter(
    (job: any) => {

      /*
      |--------------------------------------------------------------------------
      | FOGGING
      |--------------------------------------------------------------------------
      */

      if (
        viewType ===
        'fogging'
      ) {

        return (
          job.location_type_id === 8
        )
      }

      /*
      |--------------------------------------------------------------------------
      | CLEAN PLAN
      |--------------------------------------------------------------------------
      */

      return (
        job.location_type_id === 3
      )
    }
  )
}